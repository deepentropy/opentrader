import { defineConfig } from "vitest/config";
// @ts-expect-error node builtin (the project has no @types/node)
import { fileURLToPath } from "node:url";
// @ts-expect-error node builtin (the project has no @types/node)
import { existsSync } from "node:fs";
// @ts-expect-error node builtin (the project has no @types/node)
import { dirname, join } from "node:path";

// Shared drawing core: the sibling repo lightweight-charts-drawing read from source, as in vite.config.ts. A checkout
// nested in another folder (a git worktree) finds it next to the nearest parent folder that has it.
function drawingRepo(): string {
  let dir: string = fileURLToPath(new URL(".", import.meta.url));
  for (;;) {
    const candidate = join(dir, "..", "lightweight-charts-drawing");
    if (existsSync(join(candidate, "src", "core"))) return candidate;
    const parent = dirname(dir);
    if (parent === dir) return fileURLToPath(new URL("../lightweight-charts-drawing", import.meta.url));
    dir = parent;
  }
}
const drawing = drawingRepo();

// src/bindings.ts is generated by the Rust build (git-ignored): without it, `../bindings` imports (and their vi.mock
// calls) resolve to a stub so the suite runs on a fresh clone.
const bindingsStub = existsSync(fileURLToPath(new URL("./src/bindings.ts", import.meta.url)))
  ? []
  : [{ find: /^(\.\.?\/)+bindings$/, replacement: fileURLToPath(new URL("./src/__tests__/bindings-stub.ts", import.meta.url)) }];

// Unit tests of the logic layer (pure TypeScript, node environment; a test that needs the DOM opts in with a
// `// @vitest-environment jsdom` comment). Tests live in `__tests__` folders next to the code they cover.
export default defineConfig({
  resolve: {
    alias: [
      { find: /^lightweight-charts-drawing\/core/, replacement: join(drawing, "src", "core") },
      { find: /^lightweight-charts-drawing\/runtime/, replacement: join(drawing, "src", "runtime") },
      ...bindingsStub,
    ],
  },
  test: {
    include: ["src/**/__tests__/**/*.test.ts"],
    environment: "node",
    // The golden backtests run ~200 strategy runs; the other files are fast.
    testTimeout: 60_000,
  },
});
